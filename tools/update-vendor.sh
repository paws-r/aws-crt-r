#!/bin/sh
# Refresh the vendored copies of aws-checksums and aws-c-common in src/.
#
#   tools/update-vendor.sh                       # use the tags pinned below
#   CHECKSUMS_TAG=v1.0.2 COMMON_TAG=v1.0.4 tools/update-vendor.sh
#
# Only the files needed to build the CRC routines are copied (no tests, docs
# or CMake scaffolding). Headers are found by running the preprocessor in
# dependency mode over the selected sources, for several platform configs, so
# nothing is copied that is not reachable from the code we compile.
set -eu

CHECKSUMS_TAG=${CHECKSUMS_TAG:-v1.0.1}
COMMON_TAG=${COMMON_TAG:-v1.0.3}

root=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

git clone -q --depth 1 --branch "$CHECKSUMS_TAG" https://github.com/awslabs/aws-checksums "$work/ck"
git clone -q --depth 1 --branch "$COMMON_TAG" https://github.com/awslabs/aws-c-common "$work/cm"
ck_sha=$(git -C "$work/ck" rev-parse HEAD)
cm_sha=$(git -C "$work/cm" rev-parse HEAD)

CK_SRC="source/crc32.c source/crc64.c source/crc_sw.c source/crc64_sw.c source/crc_util.c
source/arm/crc32c_arm.c source/arm/crc64_arm.c
source/intel/asm/crc32c_sse42_asm.c
source/intel/intrin/crc32c_sse42_avx512.c source/intel/intrin/crc64nvme_avx512.c
source/intel/intrin/crc64nvme_clmul.c"
CM_SRC="source/arch/generic/cpuid.c source/arch/intel/cpuid.c source/arch/intel/asm/cpuid.c
source/arch/arm/darwin/cpuid.c source/arch/arm/auxv/cpuid.c"

dst="$root/src"
rm -rf "$dst/aws-checksums" "$dst/aws-c-common"
mkdir -p "$dst/aws-checksums" "$dst/aws-c-common"

for f in $CK_SRC; do mkdir -p "$dst/aws-checksums/$(dirname "$f")"; cp "$work/ck/$f" "$dst/aws-checksums/$f"; done
for f in $CM_SRC; do mkdir -p "$dst/aws-c-common/$(dirname "$f")"; cp "$work/cm/$f" "$dst/aws-c-common/$f"; done
cp "$work/ck/LICENSE" "$dst/aws-checksums/LICENSE"; cp "$work/ck/NOTICE" "$dst/aws-checksums/NOTICE" 2>/dev/null || true
cp "$work/cm/LICENSE" "$dst/aws-c-common/LICENSE"; cp "$work/cm/NOTICE" "$dst/aws-c-common/NOTICE" 2>/dev/null || true

# Header closure. config.h is generated by ./configure, so supply stand-ins.
mkdir -p "$work/cfg/aws/common"
: > "$work/cfg/aws/common/config.h"
: > "$work/deps"
for cfgdef in "-DAWS_ARCH_INTEL -DAWS_ARCH_INTEL_X64 -DAWS_USE_CPU_EXTENSIONS -DAWS_HAVE_GCC_INLINE_ASM -DAWS_HAVE_AVX2_INTRINSICS -DAWS_HAVE_AVX512_INTRINSICS -DAWS_HAVE_CLMUL -DAWS_HAVE_MM256_EXTRACT_EPI64" \
              "-DAWS_ARCH_ARM64 -DAWS_USE_CPU_EXTENSIONS -DAWS_HAVE_ARMv8_1" \
              "-D_WIN32 -DAWS_ARCH_INTEL -DAWS_ARCH_INTEL_X64" ""; do
  for f in $CK_SRC; do
    # shellcheck disable=SC2086
    ${CC:-cc} -MM -MG -I"$work/cfg" -I"$work/ck/include" -I"$work/cm/include" $cfgdef "$work/ck/$f" 2>/dev/null >> "$work/deps" || true
  done
  for f in $CM_SRC; do
    # shellcheck disable=SC2086
    ${CC:-cc} -MM -MG -I"$work/cfg" -I"$work/ck/include" -I"$work/cm/include" $cfgdef "$work/cm/$f" 2>/dev/null >> "$work/deps" || true
  done
done
tr ' \\' '\n\n' < "$work/deps" | grep -E "/include/aws/" | sort -u | while read -r h; do
  case "$h" in
    "$work/ck/include/"*) rel=${h#"$work/ck/include/"}; out="$dst/aws-checksums/include/$rel" ;;
    "$work/cm/include/"*) rel=${h#"$work/cm/include/"}; out="$dst/aws-c-common/include/$rel" ;;
    *) continue ;;
  esac
  mkdir -p "$(dirname "$out")"; cp "$h" "$out"
done

cat > "$dst/VENDORED.md" <<EOT
# Vendored sources

Refreshed by \`tools/update-vendor.sh\`. Do not edit the vendored files by hand.

| Library | Upstream | Tag | Commit |
|---|---|---|---|
| aws-checksums | https://github.com/awslabs/aws-checksums | $CHECKSUMS_TAG | $ck_sha |
| aws-c-common | https://github.com/awslabs/aws-c-common | $COMMON_TAG | $cm_sha |

Both are Apache-2.0. Only the CRC32 / CRC32C / CRC64NVME code paths are
vendored. From aws-c-common only the CPU feature detection
(\`source/arch/*/cpuid.c\`) and the headers reachable from the checksum
sources are included; \`checksums.c\`, \`xxhash.c\` and
\`aws_common_library_init\` are deliberately not built (see \`src/init.c\`).

\`aws/common/config.h\` is generated by \`./configure\` (upstream generates it
from \`config.h.in\` with CMake).
EOT
echo "aws-checksums $CHECKSUMS_TAG $ck_sha"; echo "aws-c-common  $COMMON_TAG $cm_sha"
